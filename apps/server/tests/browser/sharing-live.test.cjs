/* Opt-in acceptance against the sole GRAF Dev runtime and an operator-seeded synthetic meeting. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(require.resolve('playwright',{paths:[process.env.GRAF_NODE_MODULES || process.cwd()]}));
(async()=>{
  assert.equal(process.env.GRAF_SHARING_LIVE,'1','Only run explicitly against GRAF Dev');
  const origin='http://127.0.0.1:8081',meeting=process.argv[2],output=process.argv[3];
  assert.match(meeting,/^[0-9a-f-]{36}$/);fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const facts=[];
  let activePage=null,stage="owner_login";
  try {
    const state=process.env.GRAF_SHARING_OWNER_STATE;
    const owner=await browser.newContext({...(state&&fs.existsSync(state)?{storageState:state}:{}),permissions:['clipboard-read','clipboard-write'],viewport:{width:1440,height:1000}});
    const page=await owner.newPage();activePage=page;page.setDefaultTimeout(10000);page.on('dialog',d=>d.accept());
    await page.goto(origin+'/meetings/'+meeting);
    if(new URL(page.url()).pathname==='/login') {
    await page.locator('input[name=email]').fill('local@graf.test');
    await page.locator('form button[type=submit]').click();
    await page.locator('[data-code-slot]').first().fill('000000');
    await page.waitForURL(origin+'/meetings/'+meeting);
    if(state){fs.writeFileSync(state,JSON.stringify(await owner.storageState()),{mode:0o600});}
    }
    await page.locator('h1').filter({hasText:'Учебная встреча GRAF — проверка общего доступа'}).waitFor();
    facts.push('existing_dev_owner_login');
    await page.locator('[data-share-dialog-open]').click();
    await page.locator('[data-summary-share-dialog][open]').waitFor();
    await page.getByText('Дополнительные настройки', {exact:true}).click();
    await page.locator('[data-sharing-scope]:enabled').waitFor();
    await page.getByRole('combobox',{name:'Что доступно получателю'}).selectOption('full_meeting');
    await page.locator('[data-summary-share-dialog][aria-busy=false]').waitFor();
    await page.getByRole('button',{name:'Скопировать ссылку',exact:true}).click();
    await page.getByText('Ссылка скопирована',{exact:true}).waitFor();
    assert.equal(await page.locator('[data-sharing-audience]').inputValue(),'invite_only');
    const restricted=await page.locator('[data-summary-share-url]').inputValue();
    assert.equal(new URL(restricted).pathname,'/shared-meetings/'+meeting);
    await page.getByRole('combobox',{name:'Общий доступ',exact:true}).selectOption('link');
    await page.getByText('Общий доступ сохранён',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Скопировать ссылку',exact:true}).click();
    await page.getByText('Ссылка скопирована',{exact:true}).waitFor();
    const share=await page.locator('[data-summary-share-url]').inputValue();
    assert.equal(new URL(share).origin,origin);
    const version=await page.evaluate(()=>document.querySelector('[data-summary-share-url]').value);
    await page.getByRole('button',{name:'Скопировать ссылку',exact:true}).click();
    await page.getByText('Ссылка скопирована',{exact:true}).waitFor();
    assert.equal(await page.locator('[data-summary-share-url]').inputValue(),version);
    await page.screenshot({path:path.join(output,'owner.png'),mask:[page.locator('[data-summary-share-url]')]});
    facts.push('owner_open_explicit_full_stable_copy');
    stage='owner_export';
    await page.getByRole('tab',{name:'Экспорт',exact:true}).click();
    await page.locator('[data-export-scope]').selectOption('transcript');
    await page.locator('[data-export-format]').selectOption('txt');
    const downloading=page.waitForEvent('download');
    await page.getByRole('button',{name:'Скачать файл',exact:true}).click();
    const download=await downloading;assert.equal(await download.failure(),null);
    assert(fs.statSync(await download.path()).size>0);
    await page.getByRole('tab',{name:'Поделиться',exact:true}).click();
    facts.push('existing_owner_export_downloads_transcript');
    const guest=await browser.newContext({permissions:['clipboard-read','clipboard-write'],viewport:{width:1440,height:1000}});
    const reader=await guest.newPage();activePage=reader;stage="recipient";reader.setDefaultTimeout(10000);
    await reader.goto(share);
    await reader.getByRole('button',{name:'Посмотреть встречу',exact:true}).click();
    assert.equal(await reader.locator('[data-sharing-invite-form]').count(),0);
    await reader.getByRole('link',{name:'Расшифровка',exact:true}).click();
    await reader.getByRole('searchbox').fill('Обсудили');
    assert.equal(await reader.locator('[data-public-turn]:visible').count(),1);
    await reader.getByRole('searchbox').fill('');
    const audio=reader.locator('[data-playback-player]');
    await reader.locator('[data-public-seek]').last().click();
    await reader.waitForFunction(()=>document.querySelector('audio').readyState>=1);
    assert(Math.abs(await audio.evaluate(a=>a.currentTime)-12.5)<1);
    await reader.getByRole('button',{name:'Скорость воспроизведения',exact:true}).click();
    await reader.locator('[data-playback-speed-option="1.5"]').click();
    assert.equal(await audio.evaluate(a=>a.playbackRate),1.5);
    await audio.evaluate(a=>a.play());
    await reader.waitForFunction(()=>document.querySelector('audio').currentTime>13);
    await audio.evaluate(a=>a.pause());
    await reader.getByRole('button',{name:'Назад на 15 секунд',exact:true}).click();
    assert.equal(await audio.evaluate(a=>a.currentTime),0);
    await reader.getByRole('button',{name:'Вперед на 15 секунд',exact:true}).click();
    assert.equal(await audio.evaluate(a=>a.currentTime),15);
    await reader.screenshot({path:path.join(output,'recipient.png')});
    facts.push('anonymous_transcript_search_real_m4a_seek_play_pause_skip_speed');
    await reader.getByRole('link',{name:'Войти',exact:true}).click();
    assert.equal(new URL(reader.url()).pathname,'/login');
    assert.equal(new URL(reader.url()).searchParams.get('next'),'/shared-meeting/continue');
    await reader.locator('input[name=email]').fill('local@graf.test');
    await reader.locator('form button[type=submit]').click();
    await reader.locator('[data-code-slot]').first().fill('000000');
    await reader.waitForURL(url=>url.pathname.startsWith('/api/v1/cabinet/public-shares/'));
    assert.equal(new URL(reader.url()).hash,'#recording?position_ms=15000');
    await reader.getByRole('link',{name:'Мои встречи',exact:true}).waitFor();
    facts.push('login_returns_to_tab_and_position');
    await page.getByRole('combobox',{name:'Что доступно получателю'}).selectOption('summary_only');
    await page.getByText('Состав материалов изменён',{exact:true}).waitFor();
    await reader.reload();
    assert.equal(await reader.locator('[data-public-transcript]').count(),0);
    assert.equal(await reader.locator('audio').count(),0);
    facts.push('narrowing_removes_transcript_and_audio');
    await page.getByRole('combobox',{name:'Общий доступ',exact:true}).selectOption('invite_only');
    await page.getByText('Общий доступ сохранён',{exact:true}).waitFor();
    const denied=await reader.goto(share);assert.equal(denied.status(),404);
    facts.push('revocation_closes_same_url');
    await owner.close();await guest.close();
    fs.writeFileSync(path.join(output,'facts.json'),JSON.stringify({source_sha:process.env.GRAF_SOURCE_SHA,facts},null,2));
    console.log('GRAF Dev live sharing: '+facts.join(', ')+' PASS');
  } catch(error) {
    const parsed=activePage?new URL(activePage.url()):null;
    console.error(JSON.stringify({stage,path:parsed?.pathname.replace(/public-shares\/[^/]+/,'public-shares/[redacted]'),headings:activePage?await activePage.locator('h1').allTextContents():[]}));
    throw error;
  } finally {await browser.close();}
})().catch(e=>{console.error(e.message.replace(/https?:\/\/\S+/g,'[redacted-url]'));process.exitCode=1;});
