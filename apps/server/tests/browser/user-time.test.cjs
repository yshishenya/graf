const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const code = fs.readFileSync(require('node:path').join(__dirname, '../../src/twobrain_rec_server/cabinet/static/cabinet/user-time.js'), 'utf8');
const run = ({allow = false, cookieEnabled = true, server = 'UTC', storage = new Map(), deviceZone, preferred = ""} = {}) => {
 let saved = '', reloads = 0;
 const document = {querySelector: (q) => ({content: q.includes('graf-time-preferred') ? preferred : q.includes('graf-timezone') ? server : String(allow)})};
 Object.defineProperty(document, 'cookie', {get: () => saved, set: (v) => {if(cookieEnabled) saved = v.split(';')[0]}});
 const window = {addEventListener: () => {}};
 document.addEventListener = () => {};
 const location = {href: 'https://example.invalid/meetings?q=2026#row', protocol: 'https:', replace: (href) => {assert.equal(href, location.href); reloads++}};
 const browserIntl = {DateTimeFormat: function(locale, options) {
   return new Intl.DateTimeFormat(locale, {timeZone:deviceZone, ...options});
 }};
 vm.runInNewContext(code, {window, document, location, Intl:browserIntl, sessionStorage: {getItem:k=>storage.get(k), setItem:(k,v)=>storage.set(k,v), removeItem:k=>storage.delete(k)}});
 return {time:window.GRAFTime, reloads};
};
const {time} = run();
assert.equal(time.format('2026-09-05T21:30:00Z'), '06.09.2026, 02:30');
assert.equal(time.format('2026-09-05T21:30:00.123456'), '06.09.2026, 02:30');
assert.equal(time.format(null), 'Без даты');
assert.equal(time.format('2026-09-05'), '05.09.2026');
assert.equal(time.formatDuration(4445), '1 ч 14 мин');
assert.equal(run({allow:false}).reloads, 0);
assert.equal(run({allow:true,cookieEnabled:false}).reloads, 0);
assert.equal(run({allow:true,cookieEnabled:false}).time.format('2026-09-05T21:30:00Z'), '05.09.2026, 21:30 (UTC)');
const storage = new Map();
assert.equal(run({allow:true,storage}).reloads, 1);
assert.equal(run({allow:true,storage}).reloads, 0);
assert.equal(run({deviceZone:'UTC'}).time.format('2026-09-05T21:30:00Z'), '05.09.2026, 21:30 (UTC)');
assert.equal(run({deviceZone:'Asia/Kathmandu'}).time.format('2026-09-05T21:30:00Z'), '06.09.2026, 03:15');
const ny = run({deviceZone:'America/New_York'}).time;
assert.equal(ny.format('2026-03-08T06:30:00Z'), '08.03.2026, 01:30');
assert.equal(ny.format('2026-03-08T07:30:00Z'), '08.03.2026, 03:30');
assert.equal(ny.format('2026-09-05'), '05.09.2026');
const chosen = run({deviceZone:'Asia/Yekaterinburg',server:'America/New_York',preferred:'America/New_York',allow:true});
assert.equal(chosen.reloads,0);
assert.equal(chosen.time.timezone,'America/New_York');
assert.equal(chosen.time.format('2026-09-05T21:30:00Z'),'05.09.2026, 17:30');
assert.equal(run({preferred:'America/New_York',cookieEnabled:false,allow:true}).time.timezone,'America/New_York');
assert.equal(chosen.time.format('2026-09-05T21:30:00Z',{timeZone:'Asia/Kathmandu'}),'06.09.2026, 03:15');
assert.equal(chosen.time.timezone,'America/New_York');
assert.equal(run({preferred:'Invalid/Zone',allow:true}).time.timezone,'UTC');
assert.equal(run({preferred:'UTC',deviceZone:'Asia/Yekaterinburg',allow:true}).reloads,0);
assert.equal(ny.format('2026-11-01T05:30:00Z',{showZone:true}), '01.11.2026, 01:30 (UTC-04:00)');
assert.equal(ny.format('2026-11-01T06:30:00Z',{showZone:true}), '01.11.2026, 01:30 (UTC-05:00)');
assert.equal(chosen.time.format('2026-09-05T21:30:00Z',{timeZone:'Asia/Kathmandu',showZone:true}), '06.09.2026, 03:15 (UTC+05:45)');
console.log('user-time browser contract passed');
